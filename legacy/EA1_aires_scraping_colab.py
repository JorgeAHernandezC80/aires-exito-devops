# Limpieza rápida y eficiente de duplicados y nulos esenciales
df = df.drop_duplicates(subset='url').dropna(subset=['precio_actual']).copy()

# Extracción optimizada de capacidad (BTU) numérico directo
df['btu'] = df['nombre'].str.extract(r'(\d{4,5})\s*Btu', flags=re.I)[0].astype(float)

# Lista compactada de marcas para búsqueda directa
MARCAS = ['LG', 'Samsung', 'Mabe', 'Electrolux', 'Midea', 'Haceb', 'Whirlpool', 'Challenger', 'Kalley', 'Hyundai', 'Finlandek', 'Hisense', 'TCL', 'Carrier', 'York', 'Gree']

def detectar_marca(fila):
    nombre, texto = str(fila['nombre']), str(fila['detalles'])
    if nombre in texto:
        despues = texto.split(nombre, 1)[1].strip()
        m = re.match(r'([A-Za-zÁÉÍÓÚÑ0-9\+\.& ]{2,25}?)(?=\s+-\s|\s+\d{1,2}\s*%|\s+\$|$)', despues)
        if m and m.group(1).strip() and m.group(1).strip().lower() not in ('producto genérico', 'producto generico'):
            return m.group(1).strip().title()
    for m in MARCAS:
        if re.search(rf'\b{re.escape(m)}\b', nombre, re.I):
            return m.upper() if len(m) <= 3 else m
    return 'Otra'

df['marca'] = df.apply(detectar_marca, axis=1)
df['tipo'] = df['nombre'].apply(lambda x: 'Inverter' if 'inverter' in str(x).lower() else ('Convencional' if any(k in str(x).lower() for k in ['convencional', 'on/off', 'on-off']) else 'Otro'))
df['portatil'] = df['nombre'].str.contains('port[aá]til', case=False, regex=True)
df['descuento_calc'] = ((df['precio_anterior'] - df['precio_actual']) / df['precio_anterior'] * 100).round(1)

